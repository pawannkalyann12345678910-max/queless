-- ====================================================================
-- Queless Master Oracle SQL DDL Schema
-- Compatible with Oracle Database Cloud (OCI) & Local Engine
-- ====================================================================

-- 1. USERS TABLE
CREATE TABLE IF NOT EXISTS USERS (
    USER_ID             VARCHAR(128) PRIMARY KEY,
    EMAIL               VARCHAR(255) NOT NULL UNIQUE,
    DISPLAY_NAME        VARCHAR(255),
    PHONE               VARCHAR(30),
    PHOTO_URL           VARCHAR(500),
    PROFILE_COMPLETE    INTEGER DEFAULT 0 NOT NULL,
    ROLE                VARCHAR(30) DEFAULT 'CUSTOMER' NOT NULL,
    CREATED_AT          TEXT DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT          TEXT DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 2. ORGANIZATIONS TABLE
CREATE TABLE IF NOT EXISTS ORGANIZATIONS (
    ORG_ID              VARCHAR(64) PRIMARY KEY,
    NAME                VARCHAR(255) NOT NULL,
    CATEGORY            VARCHAR(50) NOT NULL,
    DESCRIPTION         TEXT,
    LOGO_URL            TEXT,
    BANNER_URL          TEXT,
    ADMIN_UID           VARCHAR(128) NOT NULL,
    ADMIN_EMAIL         VARCHAR(255) NOT NULL,
    SUBSCRIPTION_TIER   VARCHAR(50) DEFAULT 'STARTER' NOT NULL,
    ADDRESS             VARCHAR(500),
    CITY                VARCHAR(100),
    IS_ACTIVE           INTEGER DEFAULT 1 NOT NULL,
    CREATED_AT          TEXT DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT          TEXT DEFAULT CURRENT_TIMESTAMP NOT NULL,
    FOREIGN KEY (ADMIN_UID) REFERENCES USERS(USER_ID)
);

-- 3. QUEUES TABLE
CREATE TABLE IF NOT EXISTS QUEUES (
    QUEUE_ID            VARCHAR(64) PRIMARY KEY,
    ORG_ID              VARCHAR(64) NOT NULL,
    NAME                VARCHAR(255) NOT NULL,
    PREFIX              VARCHAR(10) DEFAULT 'Q-' NOT NULL,
    COUNTER_LABEL       VARCHAR(50) DEFAULT 'Counter 1' NOT NULL,
    AVG_SERVICE_MINS    INTEGER DEFAULT 10 NOT NULL,
    MAX_DAILY_TOKENS    INTEGER DEFAULT 0 NOT NULL,
    CURRENT_TOKEN_SEQ   INTEGER DEFAULT 0 NOT NULL,
    IS_ACTIVE           INTEGER DEFAULT 1 NOT NULL,
    IS_PAUSED           INTEGER DEFAULT 0 NOT NULL,
    OPERATING_HOURS     VARCHAR(255) DEFAULT '09:00 - 17:00' NOT NULL,
    CREATED_AT          TEXT DEFAULT CURRENT_TIMESTAMP NOT NULL,
    FOREIGN KEY (ORG_ID) REFERENCES ORGANIZATIONS(ORG_ID) ON DELETE CASCADE
);

-- 4. STAFF_ASSIGNMENTS TABLE
CREATE TABLE IF NOT EXISTS STAFF_ASSIGNMENTS (
    ASSIGNMENT_ID       VARCHAR(64) PRIMARY KEY,
    QUEUE_ID            VARCHAR(64) NOT NULL,
    ORG_ID              VARCHAR(64) NOT NULL,
    STAFF_EMAIL         VARCHAR(255) NOT NULL,
    STAFF_NAME          VARCHAR(255),
    ROLE                VARCHAR(50) DEFAULT 'OPERATOR' NOT NULL,
    CREATED_AT          TEXT DEFAULT CURRENT_TIMESTAMP NOT NULL,
    FOREIGN KEY (QUEUE_ID) REFERENCES QUEUES(QUEUE_ID) ON DELETE CASCADE,
    FOREIGN KEY (ORG_ID) REFERENCES ORGANIZATIONS(ORG_ID) ON DELETE CASCADE
);

-- 5. TOKENS TABLE
CREATE TABLE IF NOT EXISTS TOKENS (
    TOKEN_ID            VARCHAR(64) PRIMARY KEY,
    QUEUE_ID            VARCHAR(64) NOT NULL,
    ORG_ID              VARCHAR(64) NOT NULL,
    USER_ID             VARCHAR(128) NOT NULL,
    TOKEN_NUMBER        VARCHAR(30) NOT NULL,
    TOKEN_SEQ           INTEGER NOT NULL,
    CUSTOMER_NAME       VARCHAR(255) NOT NULL,
    CUSTOMER_PHONE      VARCHAR(30) NOT NULL,
    SERVICE_NOTE        VARCHAR(500),
    STATUS              VARCHAR(30) DEFAULT 'WAITING' NOT NULL, -- WAITING, CALLED, SERVING, COMPLETED, NO_SHOW, CANCELLED
    DELAY_STATUS        VARCHAR(30) DEFAULT 'NONE' NOT NULL,    -- NONE, REQUESTED_5M, APPROVED_5M, REJECTED_5M, RESCHEDULED
    DELAY_REQUESTED_AT  TEXT,
    POSITION_IN_QUEUE   INTEGER DEFAULT 0 NOT NULL,
    ESTIMATED_WAIT_MINS INTEGER DEFAULT 0 NOT NULL,
    BOOKING_DATE        VARCHAR(10) NOT NULL,
    CALLED_AT           TEXT,
    SERVE_STARTED_AT    TEXT,
    COMPLETED_AT        TEXT,
    CREATED_AT          TEXT DEFAULT CURRENT_TIMESTAMP NOT NULL,
    FOREIGN KEY (QUEUE_ID) REFERENCES QUEUES(QUEUE_ID) ON DELETE CASCADE,
    FOREIGN KEY (ORG_ID) REFERENCES ORGANIZATIONS(ORG_ID) ON DELETE CASCADE
);

-- 6. AUDIT_LOGS TABLE
CREATE TABLE IF NOT EXISTS AUDIT_LOGS (
    LOG_ID              VARCHAR(64) PRIMARY KEY,
    ORG_ID              VARCHAR(64) NOT NULL,
    QUEUE_ID            VARCHAR(64),
    TOKEN_ID            VARCHAR(64),
    ACTION              VARCHAR(100) NOT NULL,
    ACTOR_UID           VARCHAR(128) NOT NULL,
    DETAILS             VARCHAR(1000),
    DURATION_SECONDS    INTEGER DEFAULT 0,
    WAIT_SECONDS        INTEGER DEFAULT 0,
    CREATED_AT          TEXT DEFAULT CURRENT_TIMESTAMP NOT NULL
);
